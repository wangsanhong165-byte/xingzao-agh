const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const rootBounds = [[0, 0, 0], [9, 9, 9]];

function makeProbes(sourceSha256) {
  const dims = [9, 9, 9];
  const count = dims.reduce((a, b) => a * b, 1);
  const solid = Buffer.alloc(count, 1);
  const surface = Buffer.alloc(count, 0);
  const exposure = Buffer.alloc(count, 0);
  const indices = Buffer.alloc(9 * 4);
  const directions = Buffer.alloc(9, 0);
  const points = Buffer.alloc(9 * 3 * 8);
  for (let x = 0; x < 9; x += 1) {
    const index = 4 * 9 * 9 + 4 * 9 + x;
    surface[index] = 1;
    exposure[index] = 1;
    indices.writeUInt32LE(index, x * 4);
    for (let axis = 0; axis < 3; axis += 1) points.writeDoubleLE([x + 0.5, 4.5, 4.5][axis], (x * 3 + axis) * 8);
  }
  return {
    schema: 'source-feature-probes/v1', sourceSha256, sourceBoundsMm: rootBounds,
    features: [{
      id: 'rod', kind: 'solid', boundsMm: rootBounds, grid: { dimensions: dims, stepMm: [1, 1, 1], order: 'x-fastest', cellCenters: true },
      sampleCount: count, solidSampleCount: count, surfaceSampleCount: 9, surfacePointCount: 9, minRetention: 0.9, surfaceToleranceMm: 0.05,
      solidMaskBase64: solid.toString('base64'), surfaceMaskBase64: surface.toString('base64'),
      surfacePointsBase64: points.toString('base64'), surfacePointVoxelIndicesBase64: indices.toString('base64'),
      surfacePointDirectionsBase64: directions.toString('base64'), surfaceExposureMaskBase64: exposure.toString('base64'),
    }],
  };
}

function makeGcode({ gap = false } = {}) {
  const rows = ['; generated by PrusaSlicer 2.9.6+test', 'G90', 'M82', 'G92 E0', ';TYPE:External perimeter', ';WIDTH:0.45', ';HEIGHT:0.2'];
  if (gap) rows.push('G0 X86 Y90 Z4.5', 'G1 X89.5 E1', 'G0 X90.5', 'G1 X94 E2');
  else rows.push('G1 X86 Y90 Z4.5', 'G1 X94 E1');
  rows.push('; filament used [mm] = 100', '; total filament used [g] = 1', '; estimated printing time (normal mode) = 1m');
  return `${rows.join('\n')}\n`;
}

async function fixture(t, { gap = false } = {}) {
  const directory = await mkdtemp(path.join(os.tmpdir(), 'xingzao-review-check-'));
  t.after(async () => {
    const resolved = path.resolve(directory);
    assert.equal(path.dirname(resolved), path.resolve(os.tmpdir()));
    assert.match(path.basename(resolved), /^xingzao-review-check-/u);
    await rm(resolved, { recursive: true, force: true });
  });
  const caseDir = path.join(directory, 'case');
  await mkdir(caseDir, { recursive: true });
  const source = Buffer.concat(serializer.serialize({ binary: true }, modeling.transforms.translate([4.5, 4.5, 4.5], modeling.primitives.cuboid({ size: [9, 9, 9] }))).map(value => Buffer.from(value)));
  const originalSource = source;
  const rawSha = sha(source);
  const posed = createPoseCandidate({ sourceBuffer: source, poseId: 'upright' });
  const offset = { x: 90, y: 90, z: 0 };
  const gcode = makeGcode({ gap });
  const currentProbes = makeProbes(rawSha);
  const originalProbes = makeProbes(sha(originalSource));
  const files = new Map([
    ['case/cases.json', Buffer.alloc(0)], ['case/raw.stl', source], ['case/source-original.stl', originalSource],
    ['case/posed.stl', posed.buffer], ['case/result.gcode', Buffer.from(gcode)],
    ['case/probes-current.json', Buffer.from(JSON.stringify(currentProbes))], ['case/probes-original.json', Buffer.from(JSON.stringify(originalProbes))],
  ]);
  const spec = { axis: 'z', centerLineMm: [[4.5, 4.5, 1], [4.5, 4.5, 8]], allowedBoundsMm: [[3, 3, 0], [6, 6, 9]], maxRadialGrowthMm: 0.02, maxAddedVolumeMm3: 20 };
  const cases = {
    schema: 'xingzao-cached-cases/v1',
    cases: [{ id: 'normal', poseId: 'upright', source: 'case/raw.stl', originalSource: 'case/source-original.stl', posed: 'case/posed.stl', gcode: 'case/result.gcode', probes: 'case/probes-current.json', originalProbes: 'case/probes-original.json', originalSourceSha256: sha(originalSource), centerLineMm: [[0.5, 4.5, 4.5], [8.5, 4.5, 4.5]], placementOffsetMm: offset, expectedToolpathFeasible: !gap }],
    budgetFailure: { spec, inspection: { measuredRadiusMm: 0.24997, fitToleranceMm: 0.02 }, expectedOptions: [] },
  };
  files.set('case/cases.json', Buffer.from(JSON.stringify(cases)));
  for (const [name, bytes] of files) await writeFile(path.join(directory, ...name.split('/')), bytes);
  const manifest = { schema: 'xingzao-review-bundle/v1', files: [...files].map(([filePath, bytes]) => ({ path: filePath, kind: 'evidence', bytes: bytes.length, sha256: sha(bytes) })), summary: {}, claims: {} };
  await writeFile(path.join(directory, 'bundle-manifest.json'), JSON.stringify(manifest));
  return { directory, cases, files, manifest };
}

test('rechecks cached case, pose transform, actual G-code and budget options offline', async t => {
  const f = await fixture(t);
  const result = await checkReviewBundle(f.directory);
  assert.equal(result.valid, true);
  assert.equal(result.cases[0].toolpathFeasible, true);
  assert.deepEqual(result.budgetFailure.actualOptions, []);
  assert.equal(result.claims.sourceMembershipRecomputed, false);
  assert.equal(result.claims.geometryBudgetRecomputed, false);
  assert.equal(result.claims.liveModelRequestVerified, false);
  assert.equal(result.claims.physicalPrintVerified, false);
});

test('rejects a hash/byte mismatch in a listed file', async t => {
  const f = await fixture(t);
  await writeFile(path.join(f.directory, 'case', 'raw.stl'), Buffer.from('tampered'));
  await assert.rejects(checkReviewBundle(f.directory), /hash|byte/iu);
});

test('rejects manifest path traversal before file access', async t => {
  const f = await fixture(t);
  f.manifest.files[0].path = '../outside.json';
  await writeFile(path.join(f.directory, 'bundle-manifest.json'), JSON.stringify(f.manifest));
  await assert.rejects(checkReviewBundle(f.directory), /path/iu);
});

test('detects an actual gap between MODEL extrusion segments', async t => {
  const f = await fixture(t, { gap: true });
  const result=await checkReviewBundle(f.directory);
  assert.equal(result.valid,true);
  assert.equal(result.cases[0].toolpathFeasible,false);
  assert.equal(result.cases[0].audits.rodContinuity.verified,true);
  assert.ok(result.cases[0].audits.rodContinuity.maxGapMm>.5);
});

