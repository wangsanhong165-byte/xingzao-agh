test('surface points on a thin outer shell pass without requiring interior infill', () => {
  const probes = probe();
  const feature = probes.features[0];
  const pointRecords = [];
  const exposures = new Uint8Array(feature.sampleCount);
  const [nx, ny, nz] = feature.grid.dimensions;
  for (let z = 0; z < nz; z++) for (let y = 0; y < ny; y++) for (let x = 0; x < nx; x++) {
    const i = x + nx * (y + ny * z);
    const faces = [];
    if (x === 0) faces.push([0, [0, (y + 0.5), (z + 0.5)]]);
    if (x === nx - 1) faces.push([1, [nx, (y + 0.5), (z + 0.5)]]);
    if (y === 0) faces.push([2, [(x + 0.5), 0, (z + 0.5)]]);
    if (y === ny - 1) faces.push([3, [(x + 0.5), ny, (z + 0.5)]]);
    if (z === 0) faces.push([4, [(x + 0.5), (y + 0.5), 0]]);
    if (z === nz - 1) faces.push([5, [(x + 0.5), (y + 0.5), nz]]);
    for (const [direction, point] of faces) { exposures[i] |= 1 << direction; pointRecords.push({ i, direction, point }); }
  }
  const pointBytes = Buffer.alloc(pointRecords.length * 24);
  const indexBytes = Buffer.alloc(pointRecords.length * 4);
  const directionBytes = Buffer.alloc(pointRecords.length);
  pointRecords.forEach(({ i, direction, point }, p) => {
    indexBytes.writeUInt32LE(i, p * 4); directionBytes[p] = direction;
    point.forEach((coord, axis) => pointBytes.writeDoubleLE(coord, p * 24 + axis * 8));
  });
  feature.surfacePointCount = pointRecords.length;
  feature.surfaceExposureMaskBase64 = Buffer.from(exposures).toString('base64');
  feature.surfacePointsBase64 = pointBytes.toString('base64');
  feature.surfacePointVoxelIndicesBase64 = indexBytes.toString('base64');
  feature.surfacePointDirectionsBase64 = directionBytes.toString('base64');
  const topRows = [];
  for (let y = 0; y < ny; y++) for (let x = 0; x < nx; x++) topRows.push({ x: 40 + x + 0.5, y: y + 0.5, z: 4 });
  const result = auditCriticalFeatures(gcodeAt(topRows, { height: 0.4 }), options(probes));
  assert.equal(result.verified, true);
  assert.equal(result.passed, false);
  assert.equal(result.features[0].directionRetentions.find(item => item.direction === '+Z').retentionFraction, 1);
  assert.ok(result.features[0].directionRetentions.some(item => item.direction === '+X' && item.retentionFraction < 0.5));
});

test('solid surface-point payload is mandatory, exact-sized, finite, and bounded for target samples', () => {
  const variants = [];
  const missing = probe(); missing.features[0].surfacePointsBase64 = undefined; variants.push(missing);
  const short = probe(); short.features[0].surfacePointsBase64 = Buffer.from([0, 0, 0]).toString('base64'); variants.push(short);
  const nonfinite = probe();
  const nonfiniteBytes = Buffer.from(nonfinite.features[0].surfacePointsBase64, 'base64'); nonfiniteBytes.writeDoubleLE(Number.NaN, 0);
  nonfinite.features[0].surfacePointsBase64 = nonfiniteBytes.toString('base64'); variants.push(nonfinite);
  const outside = probe();
  const outsideBytes = Buffer.from(outside.features[0].surfacePointsBase64, 'base64'); outsideBytes.writeDoubleLE(5, 0);
  outside.features[0].surfacePointsBase64 = outsideBytes.toString('base64'); variants.push(outside);
  for (const probes of variants) {
    const result = auditCriticalFeatures(gcodeAt([{ x: 100, y: 100, z: 100 }]), options(probes));
    assert.equal(result.verified, false);
    assert.equal(result.features.length, 0);
  }
  const duplicate = probe();
  const indices = Buffer.from(duplicate.features[0].surfacePointVoxelIndicesBase64, 'base64');
  indices.writeUInt32LE(indices.readUInt32LE(0), 4);
  duplicate.features[0].surfacePointVoxelIndicesBase64 = indices.toString('base64');
  assert.equal(auditCriticalFeatures(gcodeAt([{ x: 100, y: 100, z: 100 }]), options(duplicate)).verified, false);
});

