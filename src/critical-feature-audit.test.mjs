test('a small extrusion plug fails a channel even when retention is above 90 percent', () => {
  const dimensions = [32, 4, 4];
  const probes = probe({ dimensions, stepMm: [0.05, 0.05, 0.05], kind: 'void-channel' });
  probes.features[0].surfaceToleranceMm = 0.05;
  const result = auditCriticalFeatures(gcodeAt([{ x: 40 + 5.5 * 0.05, y: 1.5 * 0.05, z: 1.5 * 0.05 }], { width: 0.1, height: 0.1, span: 0.001 }), options(probes));
  assert.equal(result.verified, true);
  assert.ok(result.features[0].retentionFraction > 0.9);
  assert.equal(result.features[0].connected, false);
  assert.equal(result.passed, false);
});

