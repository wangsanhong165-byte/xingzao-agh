import test from 'node:test';
import assert from 'node:assert/strict';
import { parseGcodeSegments } from './slicer.mjs';

const body = ['G21', 'G90', 'M83', 'G1 X0 Y0 Z2.2', ';TYPE:Perimeter', ';WIDTH:0.45', 'G1 X2 E1', ';TYPE:External perimeter', 'G1 Y2 E1', ';WIDTH:0.4', 'G1 X0 E1'].join('\n');
test('PrusaSlicer 2.9.6 width tags persist across TYPE changes until the next WIDTH tag', () => {
  const parsed = parseGcodeSegments('; generated by PrusaSlicer 2.9.6 on 2026-10-02\n' + body);
  assert.deepEqual(parsed.segments.filter(segment => segment.motionType === 'extrusion').map(segment => segment.lineWidthMm), [.45, .45, .4]);
});
test('unknown generators cannot infer width persistence merely from a previous role', () => {
  const parsed = parseGcodeSegments(body);
  assert.deepEqual(parsed.segments.filter(segment => segment.motionType === 'extrusion').map(segment => segment.lineWidthMm), [.45, null, .4]);
});
