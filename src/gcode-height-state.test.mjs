import test from 'node:test';
import assert from 'node:assert/strict';
import {parseGcodeSegments} from './slicer.mjs';

test('verified Prusa HEIGHT persists independently of TYPE until changed',()=>{
  const gcode='; generated by PrusaSlicer 2.9.6 on test\nG90\nM83\nG1 X0 Y0 Z1\n;TYPE:External perimeter\n;WIDTH:0.45\n;HEIGHT:0.2\nG1 X5 E1\n;TYPE:Solid infill\nG1 Y5 E1\n;HEIGHT:0.1\nG1 X0 E1\n';
  const moves=parseGcodeSegments(gcode).segments.filter(s=>s.motionType==='extrusion');
  assert.deepEqual(moves.map(s=>s.lineHeightMm),[.2,.2,.1]);
});

test('unknown generators reset HEIGHT on role changes and invalid tags remove stale height',()=>{
  const gcode='G90\nM83\nG1 X0 Y0 Z1\n;TYPE:External perimeter\n;WIDTH:0.45\n;HEIGHT:0.2\nG1 X5 E1\n;TYPE:Solid infill\n;WIDTH:0.45\nG1 Y5 E1\n;HEIGHT:0.2\nG1 X0 E1\n;HEIGHT:invalid\nG1 Y0 E1\n';
  const moves=parseGcodeSegments(gcode).segments.filter(s=>s.motionType==='extrusion');
  assert.deepEqual(moves.map(s=>s.lineHeightMm),[.2,null,.2,null]);
});
test('invalid WIDTH tags remove stale widths before feature-envelope checks',()=>{
  const gcode='; generated by PrusaSlicer 2.9.6 on test\nM83\nG1 X0 Y0 Z1\n;TYPE:External perimeter\n;WIDTH:0.4\n;HEIGHT:0.2\nG1 X1 E1\n;WIDTH:invalid\nG1 X2 E1\n;WIDTH:-0.4\nG1 X3 E1\n';
  assert.deepEqual(parseGcodeSegments(gcode).segments.filter(s=>s.motionType==='extrusion').map(s=>s.lineWidthMm),[.4,null,null]);
});
