function finite(value, label) {
  if (typeof value !== 'number' || !Number.isFinite(value)) throw new TypeError(`${label} must be finite`);
  return value;
}

function roiBounds(bounds) {
  let result;
  if (Array.isArray(bounds) && bounds.length === 4) {
    result = { xMin: bounds[0], yMin: bounds[1], xMax: bounds[2], yMax: bounds[3] };
  } else {
    if (!bounds || typeof bounds !== 'object') throw new TypeError('featureBoundsMm is required');
    const xMin = bounds.xMin ?? bounds.minX ?? bounds.min?.[0] ?? bounds.x;
    const yMin = bounds.yMin ?? bounds.minY ?? bounds.min?.[1] ?? bounds.y;
    const xMax = bounds.xMax ?? bounds.maxX ?? bounds.max?.[0] ?? (Number.isFinite(bounds.width) ? xMin + bounds.width : undefined);
    const yMax = bounds.yMax ?? bounds.maxY ?? bounds.max?.[1] ?? (Number.isFinite(bounds.height) ? yMin + bounds.height : undefined);
    result = { xMin, yMin, xMax, yMax };
  }
  for (const [key, value] of Object.entries(result)) finite(value, `featureBoundsMm.${key}`);
  if (result.xMax <= result.xMin || result.yMax <= result.yMin) throw new RangeError('featureBoundsMm must have positive width and height');
  return result;
}

function clipSegment(start, end, rect) {
  const dx = end.x - start.x;
  const dy = end.y - start.y;
  let t0 = 0;
  let t1 = 1;
  const tests = [
    [-dx, start.x - rect.xMin],
    [dx, rect.xMax - start.x],
    [-dy, start.y - rect.yMin],
    [dy, rect.yMax - start.y],
  ];
  for (const [p, q] of tests) {
    if (Math.abs(p) < 1e-12) {
      if (q < 0) return null;
      continue;
    }
    const ratio = q / p;
    if (p < 0) t0 = Math.max(t0, ratio);
    else t1 = Math.min(t1, ratio);
    if (t0 > t1) return null;
  }
  return {
    t0,
    t1,
    start: { x: start.x + dx * t0, y: start.y + dy * t0 },
    end: { x: start.x + dx * t1, y: start.y + dy * t1 },
  };
}

function svgPreview(rect, segments) {
  const width = 640;
  const height = 640;
  const sx = width / (rect.xMax - rect.xMin);
  const sy = height / (rect.yMax - rect.yMin);
  const point = (x, y) => `${((x - rect.xMin) * sx).toFixed(2)},${(height - (y - rect.yMin) * sy).toFixed(2)}`;
  const paths = segments.map(({ start, end, z }) =>
    `<path d="M ${point(start.x, start.y)} L ${point(end.x, end.y)}" stroke="${z > 0 ? '#d43b67' : '#888'}" stroke-width="1.5" fill="none" data-z="${z.toFixed(3)}"/>`,
  ).join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" width="640" height="640" viewBox="0 0 640 640"><rect width="640" height="640" fill="white"/><rect x="1" y="1" width="638" height="638" fill="none" stroke="#bbb" stroke-width="2"/>${paths}</svg>`;
}

function classifyGcodeFeature(sourceRole) {
  if (!sourceRole) return 'UNKNOWN';
  const label = sourceRole.toLowerCase().replace(/[_-]+/g, ' ').trim();
  if (/support|raft/.test(label)) return 'SUPPORT';
  if (/skirt|brim/.test(label)) return 'SKIRT_BRIM';
  if (/wipe tower|purge/.test(label)) return 'AUXILIARY';
  if (/perimeter|wall|infill|bridge|gap fill|ironing|overhang|solid surface|top surface|bottom surface/.test(label)) return 'MODEL';
  return 'UNKNOWN';
}

/** Parse linear toolpath moves and retain slicer role/width comments. */
export function parseGcodeSegments(gcodeText) {
  if (typeof gcodeText !== 'string') throw new TypeError('gcodeText must be a string');
  // PrusaSlicer 2.9.6 GCode.cpp emits WIDTH only when path_attr.width changes,
  // independently of TYPE. Unknown generators retain conservative role resets.
  const widthPersistsAcrossRoles = /^; generated by PrusaSlicer 2\.9\.6(?:\+|\s)/m.test(gcodeText);
  const position = { x: 0, y: 0, z: 0 };
  const axisOffset = { x: 0, y: 0, z: 0 };
  let xyzAbsolute = true;
  let eAbsolute = true;
  let ePosition = 0;
  let unitsToMm = 1;
  let sourceRole = null;
  let featureRole = 'UNKNOWN';
  let currentWidthMm = null;
  let currentHeightMm = null;
  let unsupportedArcMoves = 0;
  const segments = [];

  for (const rawLine of gcodeText.split(/\r?\n/)) {
    const commentAt = rawLine.indexOf(';');
    const codeText = (commentAt < 0 ? rawLine : rawLine.slice(0, commentAt)).trim().toUpperCase();
    if (commentAt >= 0) {
      const comment = rawLine.slice(commentAt + 1).trim();
      const roleMatch = comment.match(/^(?:TYPE|FEATURE)\s*:\s*(.+)$/i);
      if (roleMatch) {
        sourceRole = roleMatch[1].trim();
        featureRole = classifyGcodeFeature(sourceRole);
        if (!widthPersistsAcrossRoles) { currentWidthMm = null; currentHeightMm = null; }
      }
      const widthMatch = comment.match(/^(?:WIDTH|EXTRUSION_WIDTH)\s*:\s*(.*)$/i);
      if (widthMatch) {
        const parsedWidth = Number(widthMatch[1]);
        currentWidthMm = Number.isFinite(parsedWidth) && parsedWidth > 0 ? parsedWidth : null;
      }
      const heightMatch = comment.match(/^(?:HEIGHT|LAYER_HEIGHT)\s*:\s*(.*)$/i);
      if (heightMatch) {
        const parsedHeight = Number(heightMatch[1]);
        currentHeightMm = Number.isFinite(parsedHeight) && parsedHeight > 0 ? parsedHeight : null;
      }
    }
    if (!codeText) continue;
    const commandMatch = codeText.match(/(?:^|\s|\*)((?:G|M|T)\s*\d+(?:\.\d+)?)(?=\s|\*|$)/);
    if (!commandMatch) continue;
    const command = commandMatch[1].replace(/\s+/g, '');
    const words = Object.create(null);
    for (const match of codeText.matchAll(/([XYZEF])\s*([-+]?(?:\d+(?:\.\d*)?|\.\d+)(?:E[-+]?\d+)?)/g)) {
      words[match[1]] = Number(match[2]);
    }
    if (command === 'G20') { unitsToMm = 25.4; continue; }
    if (command === 'G21') { unitsToMm = 1; continue; }
    if (command === 'G90') { xyzAbsolute = true; continue; }
    if (command === 'G91') { xyzAbsolute = false; continue; }
    if (command === 'M82') { eAbsolute = true; continue; }
    if (command === 'M83') { eAbsolute = false; continue; }
    if (command === 'G92') {
      for (const axis of ['X', 'Y', 'Z']) {
        if (words[axis] !== undefined) axisOffset[axis.toLowerCase()] = position[axis.toLowerCase()] - words[axis] * unitsToMm;
      }
      if (words.E !== undefined) ePosition = words.E * unitsToMm;
      continue;
    }
    if (command !== 'G0' && command !== 'G00' && command !== 'G1' && command !== 'G01') {
      if (/^G(?:2|3|02|03)$/.test(command) && words.E !== undefined) unsupportedArcMoves += 1;
      continue;
    }

    const start = { ...position };
    const end = { ...position };
    for (const axis of ['X', 'Y', 'Z']) {
      if (words[axis] === undefined) continue;
      const key = axis.toLowerCase();
      const value = words[axis] * unitsToMm;
      end[key] = xyzAbsolute ? value + axisOffset[key] : position[key] + value;
    }
    let deltaE = 0;
    if (words.E !== undefined) {
      const value = words.E * unitsToMm;
      if (eAbsolute) {
        deltaE = value - ePosition;
        ePosition = value;
      } else {
        deltaE = value;
        ePosition += value;
      }
    }
    Object.assign(position, end);
    const xyLengthMm = Math.hypot(end.x - start.x, end.y - start.y);
    const zDeltaMm = end.z - start.z;
    let motionType;
    let role;
    if (deltaE < -1e-7) { motionType = 'retraction'; role = 'RETRACTION'; }
    else if (deltaE > 1e-7 && xyLengthMm > 1e-7) { motionType = 'extrusion'; role = featureRole; }
    else if (deltaE > 1e-7) { motionType = 'prime'; role = 'PRIME'; }
    else if (Math.abs(zDeltaMm) > 1e-7) { motionType = 'zhop'; role = 'ZHOP'; }
    else if (xyLengthMm > 1e-7) { motionType = 'travel'; role = 'TRAVEL'; }
    else continue;
    segments.push({ start, end, deltaEMm: deltaE, xyLengthMm, motionType, role, sourceRole, lineWidthMm: currentWidthMm, lineHeightMm: currentHeightMm });
  }
  return { segments, unsupportedArcMoves };
}

/**
 * Analyze actual G-code extrusion moves in the local feature region.
 * featureBoundsMm is model-local; placementOffsetMm translates it to the
 * slicer's build-plate coordinates.
 */
export function analyzeDetailPaths(gcodeText, options = {}) {
  if (typeof gcodeText !== 'string') throw new TypeError('gcodeText must be a string');
  const baseZ = finite(options.baseZ, 'baseZ');
  const nozzleDiameter = finite(options.nozzleDiameter, 'nozzleDiameter');
  if (nozzleDiameter <= 0) throw new RangeError('nozzleDiameter must be positive');
  const local = roiBounds(options.featureBoundsMm);
  const placement = options.placementOffsetMm ?? { x: 0, y: 0, z: 0 };
  const offset = {
    x: finite(placement.x ?? placement[0] ?? 0, 'placementOffsetMm.x'),
    y: finite(placement.y ?? placement[1] ?? 0, 'placementOffsetMm.y'),
    z: finite(placement.z ?? placement[2] ?? 0, 'placementOffsetMm.z'),
  };
  const rect = { xMin: local.xMin + offset.x, xMax: local.xMax + offset.x, yMin: local.yMin + offset.y, yMax: local.yMax + offset.y };

  const parsed = parseGcodeSegments(gcodeText);
  const raisedSegments = [];
  let raisedLength = 0;
  let highestExtrusionZ = null;
  const layerKeys = new Set();
  let extrusionBounds = null;

  for (const segment of parsed.segments) {
    if (segment.motionType !== 'extrusion') continue;
    const { start, end, xyLengthMm: xyLength } = segment;
    const machineStart = { x: start.x, y: start.y, z: start.z + offset.z };
    const machineEnd = { x: end.x, y: end.y, z: end.z + offset.z };
    if (!extrusionBounds) {
      extrusionBounds = { xMin: Infinity, yMin: Infinity, zMin: Infinity, xMax: -Infinity, yMax: -Infinity, zMax: -Infinity };
    }
    for (const point of [machineStart, machineEnd]) {
      extrusionBounds.xMin = Math.min(extrusionBounds.xMin, point.x); extrusionBounds.xMax = Math.max(extrusionBounds.xMax, point.x);
      extrusionBounds.yMin = Math.min(extrusionBounds.yMin, point.y); extrusionBounds.yMax = Math.max(extrusionBounds.yMax, point.y);
      extrusionBounds.zMin = Math.min(extrusionBounds.zMin, point.z); extrusionBounds.zMax = Math.max(extrusionBounds.zMax, point.z);
    }
    const clipped = clipSegment(start, end, rect);
    if (!clipped || clipped.t1 - clipped.t0 <= 1e-8) continue;
    const zStart = start.z + offset.z + (end.z - start.z) * clipped.t0;
    const zEnd = start.z + offset.z + (end.z - start.z) * clipped.t1;
    const zMid = (zStart + zEnd) * 0.5;
    if (zMid <= baseZ + 0.01) continue;
    const segmentLength = xyLength * (clipped.t1 - clipped.t0);
    if (segmentLength <= 0.01) continue;
    raisedLength += segmentLength;
    highestExtrusionZ = Math.max(highestExtrusionZ ?? -Infinity, zStart, zEnd);
    const layer = Math.round(zMid * 1000);
    layerKeys.add(layer);
    raisedSegments.push({ ...clipped, z: zMid });
  }

  const featureLayerCount = layerKeys.size;
  const hasRaisedDetail = raisedLength >= Math.max(0.5, nozzleDiameter * 2) && featureLayerCount > 0;
  const checks = [{
    name: 'raised-detail-path',
    status: hasRaisedDetail ? 'pass' : 'fail',
    detail: hasRaisedDetail
      ? `Found ${raisedLength.toFixed(2)} mm of positive extrusion in ${featureLayerCount} layer(s) above baseZ.`
      : 'No sufficient positive extrusion was found above baseZ inside the translated feature ROI.',
  }];
  if (parsed.unsupportedArcMoves) checks.push({ name: 'unsupported-arc-extrusions', status: 'warning', detail: `${parsed.unsupportedArcMoves} G2/G3 extrusion move(s) were not included in path length.` });
  return {
    featureExtrusionLengthMm: Number(raisedLength.toFixed(3)),
    featureLayerCount,
    highestExtrusionZ: highestExtrusionZ === null ? null : Number(highestExtrusionZ.toFixed(3)),
    hasRaisedDetail,
    extrusionBoundsMm: extrusionBounds ? Object.fromEntries(Object.entries(extrusionBounds).map(([key, value]) => [key, Number(value.toFixed(4))])) : null,
    previewSvg: svgPreview(rect, raisedSegments),
    checks,
  };
}

function isInsideAllowedPath(candidate) {
  const absolute = path.resolve(candidate);
  const relative = path.relative(PROJECT_ROOT, absolute);
  return relative && !relative.startsWith(`..${path.sep}`) && relative !== '..' && !path.isAbsolute(relative)
    && (relative.startsWith(`data${path.sep}`) || relative.startsWith(`tests${path.sep}`));
}

export async function getSlicerStatus({ profileId = PROFILE_ID } = {}) {
  if (!PROFILE_IDS.has(profileId)) throw new RangeError(`Unsupported profileId: ${profileId}`);
  if (!statusPromises.has(profileId)) {
    statusPromises.set(profileId, (async () => {
      const profilePath = profilePathFor(profileId);
      const profileExists = await stat(profilePath).then(() => true, () => false);
      let executable = null;
      for (const candidate of SLICER_CANDIDATES) {
        if (await stat(candidate).then((value) => value.isFile(), () => false)) { executable = candidate; break; }
      }
      let version = 'not installed';
      if (executable) {
        const result = await runProcess(executable, ['--help']);
        const help = `${result.stdout}\n${result.stderr}`;
        version = help.match(/PrusaSlicer[- ](\d+\.\d+\.\d+)/)?.[0] ?? help.trim().split(/\r?\n/)[0];
      }
      return {
        available: Boolean(executable && profileExists),
        profileId,
        profile: { ...VIRTUAL_PROFILE, id: profileId, automaticSupport: profileId === 'fdm-pla-04-auto-support' },
        mode: 'actual-slicer',
        version,
        executable,
        tool: { name: 'PrusaSlicer', source: 'https://github.com/prusa3d/PrusaSlicer/releases/tag/version_2.9.6', license: 'GNU AGPL-3.0 (official source LICENSE)' },
        profilePath,
        warnings: ['This is a virtual slicing profile, not a claim that a matching physical printer is configured.'],
      };
    })());
  }
  return statusPromises.get(profileId);
}

function runProcess(executable, args, timeoutMs = 120_000) {
  return new Promise((resolve, reject) => {
    const child = spawn(executable, args, { windowsHide: true, shell: false, cwd: PROJECT_ROOT });
    let stdout = '';
    let stderr = '';
    let timedOut = false;
    const timer = setTimeout(() => { timedOut = true; child.kill(); }, timeoutMs);
    child.stdout.setEncoding('utf8').on('data', (chunk) => { if (stdout.length < 500_000) stdout += chunk; });
    child.stderr.setEncoding('utf8').on('data', (chunk) => { if (stderr.length < 500_000) stderr += chunk; });
    child.on('error', (error) => { clearTimeout(timer); reject(error); });
    child.on('close', (code) => {
      clearTimeout(timer);
      if (timedOut) return reject(new Error('Slicer timed out after 120 seconds'));
      if (code !== 0) return reject(new Error(`Slicer exited with code ${code}: ${stderr.slice(-4000)}`));
      resolve({ stdout, stderr, code });
    });
  });
}

export async function sliceArtifact({ stlPath, outputDir, profileId = PROFILE_ID }) {
  if (!PROFILE_IDS.has(profileId)) throw new RangeError(`Unsupported profileId: ${profileId}`);
  if (!stlPath || !isInsideAllowedPath(stlPath)) throw new RangeError('stlPath must be under project data/ or tests/');
  if (!outputDir || !isInsideAllowedPath(path.join(outputDir, 'result.gcode'))) throw new RangeError('outputDir must be under project data/ or tests/');
  const status = await getSlicerStatus({ profileId });
  if (!status.available) throw new Error('PrusaSlicer or the fdm-pla-04.ini profile is unavailable');
  const sourcePath = await realpath(stlPath);
  if (!isInsideAllowedPath(sourcePath)) throw new RangeError('Resolved stlPath must stay under project data/ or tests/');
  await stat(sourcePath).then((value) => { if (!value.isFile()) throw new Error('STL input must be a file'); });
  await mkdir(outputDir, { recursive: true });
  const safeOutputDir = await realpath(outputDir);
  if (!isInsideAllowedPath(path.join(safeOutputDir, 'result.gcode'))) throw new RangeError('Resolved outputDir must stay under project data/ or tests/');
  const gcodePath = path.join(safeOutputDir, 'result.gcode');
  const sourceBytes = await readFile(sourcePath);
  const profileBytes = await readFile(status.profilePath);
  // CLI flags/profile options are fixed to the verified PrusaSlicer invocation.
  await mkdir(SLICER_DATA_DIR, { recursive: true });
  await runProcess(status.executable, [
    '--datadir', SLICER_DATA_DIR,
    '--load', status.profilePath,
    '--export-gcode',
    '--center', '90,90',
    '--output', gcodePath,
    sourcePath,
  ]);
  const gcode = await readFile(gcodePath, 'utf8');
  const stl = await readFile(sourcePath);
  if (hash(stl) !== hash(sourceBytes) || hash(await readFile(status.profilePath)) !== hash(profileBytes))
    throw new Error('Slicer input or profile changed during execution');
  const bounds = stlBounds(stl);
  const placementOffsetMm = {
    x: Number((90 - (bounds.xMin + bounds.xMax) / 2).toFixed(4)),
    y: Number((90 - (bounds.yMin + bounds.yMax) / 2).toFixed(4)),
    z: Number(Math.max(0, -bounds.zMin).toFixed(4)),
  };
  // Support and brim can be asymmetric. Only model paths provide a coarse
  // placement cross-check; they do not prove local surface fidelity.
  let gcodeBounds = null;
  for (const segment of parseGcodeSegments(gcode).segments) {
    if (segment.motionType !== 'extrusion' || segment.role !== 'MODEL') continue;
    if (!gcodeBounds) gcodeBounds = {xMin:Infinity,yMin:Infinity,zMin:Infinity,xMax:-Infinity,yMax:-Infinity,zMax:-Infinity};
    for (const point of [segment.start, segment.end]) for (const axis of ['x','y','z']) {
      gcodeBounds[`${axis}Min`] = Math.min(gcodeBounds[`${axis}Min`],point[axis]);
      gcodeBounds[`${axis}Max`] = Math.max(gcodeBounds[`${axis}Max`],point[axis]);
    }
  }
  const observedCenter = gcodeBounds ? {
    x: Number(((gcodeBounds.xMin + gcodeBounds.xMax) / 2).toFixed(4)),
    y: Number(((gcodeBounds.yMin + gcodeBounds.yMax) / 2).toFixed(4)),
  } : null;
  const metrics = parseSlicerMetrics(gcode);
  const config = Object.fromEntries(profileBytes.toString('utf8').split(/\r?\n/).filter(line=>/^[^#;][^=]*=/.test(line)).map(line=>{
    const index=line.indexOf('='); return [line.slice(0,index).trim(),line.slice(index+1).trim()];
  }));
  const expectedSupport = profileId === 'fdm-pla-04-auto-support';
  const actualSupport = gcode.match(/^;\s*support_material\s*=\s*([01])\s*$/mu)?.[1];
  if (config.support_material !== (expectedSupport?'1':'0') || actualSupport !== config.support_material)
    throw new Error('Slicer support setting was not verified in output');
  return {
    gcodePath,
    metrics,
    profile: { ...status.profile },
    proof: {
      sourceStlSha256: hash(stl), profileId, profileSha256: hash(profileBytes), gcodeSha256: hash(Buffer.from(gcode)),
      settings: {supportMaterial: expectedSupport,automaticSupport:config.support_material_auto==='1',layerHeightMm:Number(config.layer_height),nozzleDiameterMm:Number(config.nozzle_diameter),perimeters:Number(config.perimeters),fillDensity:config.fill_density,fillPattern:config.fill_pattern,perimeterGenerator:config.perimeter_generator},
    },
    placementOffsetMm,
    placementVerification: {
      requestedCenterMm: { x: 90, y: 90 },
      observedExtrusionBoundsMm: gcodeBounds,
      observedExtrusionCenterMm: observedCenter,
      modelPathsUsed: true,
      centeredAtRequestedPoint: Boolean(observedCenter && Math.abs(observedCenter.x - 90) <= 0.6 && Math.abs(observedCenter.y - 90) <= 0.6),
    },
    sourceStlBoundsMm: bounds,
    execution: { mode: 'actual-slicer', version: status.version },
    warnings: [
      'Slicing estimates use a virtual 180×180×180 mm FDM PLA profile and do not validate a real printer or physical print.',
      'STL is centered at the virtual bed center using the explicit verified --center 90,90 argument.',
    ],
  };
}

function stlBounds(buffer) {
  if (buffer.length < 84) throw new Error('Invalid STL: file is too short');
  const count = buffer.readUInt32LE(80);
  if (84 + count * 50 === buffer.length) {
    const result = { xMin: Infinity, yMin: Infinity, zMin: Infinity, xMax: -Infinity, yMax: -Infinity, zMax: -Infinity };
    for (let triangle = 0; triangle < count; triangle += 1) {
      const base = 84 + triangle * 50 + 12;
      for (let vertex = 0; vertex < 3; vertex += 1) {
        const x = buffer.readFloatLE(base + vertex * 12);
        const y = buffer.readFloatLE(base + vertex * 12 + 4);
        const z = buffer.readFloatLE(base + vertex * 12 + 8);
        result.xMin = Math.min(result.xMin, x); result.xMax = Math.max(result.xMax, x);
        result.yMin = Math.min(result.yMin, y); result.yMax = Math.max(result.yMax, y);
        result.zMin = Math.min(result.zMin, z); result.zMax = Math.max(result.zMax, z);
      }
    }
    if (count) return result;
  }
  const text = buffer.toString('utf8');
  const matches = [...text.matchAll(/vertex\s+([-+\d.eE]+)\s+([-+\d.eE]+)\s+([-+\d.eE]+)/g)];
  if (!matches.length) throw new Error('Invalid STL: no triangle vertices');
  const vertices = matches.map((match) => match.slice(1).map(Number));
  return {
    xMin: Math.min(...vertices.map((v) => v[0])), yMin: Math.min(...vertices.map((v) => v[1])), zMin: Math.min(...vertices.map((v) => v[2])),
    xMax: Math.max(...vertices.map((v) => v[0])), yMax: Math.max(...vertices.map((v) => v[1])), zMax: Math.max(...vertices.map((v) => v[2])),
  };
}

export function parseSlicerMetrics(gcode) {
  const numberAfter = (pattern) => {
    const match = gcode.match(pattern);
    return match ? Number(match[1]) : null;
  };
  const filamentMm = numberAfter(/^;\s*filament used \[mm\]\s*=\s*([\d.]+)/im);
  const filamentGFromSlicer = numberAfter(/^;\s*total filament used \[g\]\s*=\s*([\d.]+)/im)
    ?? numberAfter(/^;\s*filament used \[g\]\s*=\s*([\d.]+)/im);
  const filamentCm3 = numberAfter(/^;\s*filament used \[cm3\]\s*=\s*([\d.]+)/im);
  const estimatedTime = gcode.match(/^;\s*estimated printing time(?: \([^\n)]*\))?\s*=\s*([^\r\n]+)/im);
  const estimatedTimeSeconds = estimatedTime ? parseDuration(estimatedTime[1]) : null;
  let filamentG = filamentGFromSlicer;
  let massDerived = false;
  if (filamentG === null && filamentCm3 !== null) filamentG = filamentCm3 * VIRTUAL_PROFILE.filamentDensityGPerCm3;
  if (filamentG === null && filamentMm !== null) {
    const areaMm2 = Math.PI * (VIRTUAL_PROFILE.filamentDiameterMm / 2) ** 2;
    filamentG = filamentMm * areaMm2 * VIRTUAL_PROFILE.filamentDensityGPerCm3 / 1000;
    massDerived = true;
  }
  return {
    filamentMm: filamentMm === null ? null : Number(filamentMm.toFixed(2)),
    filamentG: filamentG === null ? null : Number(filamentG.toFixed(2)),
    estimatedTimeSeconds,
    ...(massDerived ? { massDerivedFromSlicerLength: true } : {}),
  };
}

function parseDuration(value) {
  const input = value.trim().toLowerCase();
  let total = 0;
  const pattern = /(\d+(?:\.\d+)?)\s*(d|days?|h|hours?|m|minutes?|s|seconds?)/g;
  const matches = [...input.matchAll(pattern)];
  if (!matches.length) return null;
  for (const [, raw, unit] of matches) {
    const amount = Number(raw);
    if (unit.startsWith('d')) total += amount * 86400;
    else if (unit.startsWith('h')) total += amount * 3600;
    else if (unit.startsWith('m')) total += amount * 60;
    else total += amount;
  }
  return Number.isFinite(total) ? Math.round(total) : null;
}
